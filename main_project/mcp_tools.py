# ============================================
# Postgres — pooled connections, statement timeout, write guardrail
# ============================================

STATEMENT_TIMEOUT_MS = int(os.getenv("PG_STATEMENT_TIMEOUT_MS", "15000"))  # 15s default
LARGE_WRITE_ROW_THRESHOLD = int(os.getenv("PG_LARGE_WRITE_ROW_THRESHOLD", "10"))

_pg_pool = pg_pool.ThreadedConnectionPool(
    minconn=1,
    maxconn=int(os.getenv("PG_POOL_MAXCONN", "10")),
    dbname=os.getenv("POSTGRES_DB"),
    user=os.getenv("POSTGRES_USER"),
    password=os.getenv("POSTGRES_PASSWORD"),
    host=os.getenv("POSTGRES_HOST"),
    port=os.getenv("POSTGRES_PORT"),
)


def get_connection():
    """
    Kept for backward compatibility with code (agent.py) that calls this
    directly for its own cursors (e.g. sync_single_user, create_user,
    preview_delete, confirm_revert). Returns a pooled connection — callers
    are responsible for calling release_connection(conn) instead of
    conn.close().
    """
    conn = _pg_pool.getconn()
    _apply_statement_timeout(conn)
    return conn


def release_connection(conn):
    """Return a connection to the pool instead of closing it outright."""
    try:
        _pg_pool.putconn(conn)
    except Exception:
        logger.exception("Failed to return connection to pool; closing it instead.")
        try:
            conn.close()
        except Exception:
            pass


def _apply_statement_timeout(conn):
    try:
        with conn.cursor() as cur:
            cur.execute(f"SET statement_timeout = {STATEMENT_TIMEOUT_MS};")
        conn.commit()
    except Exception:
        logger.exception("Failed to apply statement_timeout on connection.")


_WRITE_START_RE = re.compile(r"^\s*(INSERT|UPDATE|DELETE)\b", re.IGNORECASE)


@contextmanager
def _pooled_cursor():
    conn = get_connection()
    cur = conn.cursor()
    try:
        yield conn, cur
    finally:
        cur.close()
        try:
            conn.rollback()
        except Exception:
            pass
        release_connection(conn)


def _is_write_statement(sql: str) -> bool:
    return bool(_WRITE_START_RE.match(normalize_sql(sql)))


def query_postgres(sql: str, user_id: int, confirm: bool = False) -> str:
    try:
        safe_user_id = int(user_id)
    except (TypeError, ValueError):
        return "ERROR: no verified user for this request; query not run."

    if not isinstance(sql, str) or not is_single_statement(sql):
        return "ERROR: only one plain SQL statement is allowed."

    if has_sql_comment(sql):
        return "ERROR: SQL comments are not allowed."

    norm = normalize_sql(sql)
    is_write = bool(_WRITE_START_RE.match(norm))

    if is_write:
        if _DANGEROUS_FUNC_RE.search(norm):
            return "ERROR: this statement is not allowed."
        role = "agent_writer"
    else:
        if not is_read_only_query(sql):
            return "ERROR: only plain read queries, or a single INSERT/UPDATE/DELETE, are allowed."
        role = "agent_reader"

    try:
        with _pooled_cursor() as (conn, cur):
            if not is_write:
                cur.execute("SET TRANSACTION READ ONLY")
            cur.execute(f"SET LOCAL ROLE {role}")
            cur.execute("SELECT set_config('app.user_id', %s, true)", (str(safe_user_id),))

            cur.execute(sql)

            if is_write:
                rows = cur.rowcount
                if not confirm and rows > LARGE_WRITE_ROW_THRESHOLD:
                    conn.rollback()
                    return (
                        f"CONFIRMATION_REQUIRED: This statement would affect {rows} rows, "
                        f"above the safety threshold of {LARGE_WRITE_ROW_THRESHOLD}. "
                        f"Nothing was changed. Show this row count to the user and only "
                        f"re-run with an explicit confirmation."
                    )
                returned = str(cur.fetchall()) if cur.description else None
                conn.commit()
                return returned or f"OK, {rows} row(s) affected."

            result = str(cur.fetchall()) if cur.description else "OK."
            conn.commit()
            return result

    except Exception as e:
        logger.exception("query_postgres failed.")
        return f"ERROR: {str(e)}"


def _prepare_read(cur, as_user_id):
    cur.execute("SET TRANSACTION READ ONLY")              # must be first in the transaction
    if as_user_id is not None:
        cur.execute("SET LOCAL ROLE agent_writer")        # same view the write will have
        cur.execute("SELECT set_config('app.user_id', %s, true)", (str(int(as_user_id)),))


def fetch_rows(sql: str, limit_rows: int = None, as_user_id: int = None) -> list:
    with _pooled_cursor() as (conn, cur):
        _prepare_read(cur, as_user_id)
        cur.execute(sql)
        columns = [desc[0] for desc in cur.description]
        rows = cur.fetchall()
        conn.commit()
        result = [dict(zip(columns, row)) for row in rows]
        return result[:limit_rows] if limit_rows is not None else result


def count_rows(sql: str, as_user_id: int = None) -> int:
    with _pooled_cursor() as (conn, cur):
        _prepare_read(cur, as_user_id)
        cur.execute(sql)
        row = cur.fetchone()
        conn.commit()
        return int(row[0]) if row and row[0] is not None else 0

# ============================================
# Audit log — who did what, when
# ============================================
# Requires the audit_log table (created once, as the postgres admin user).
# app_agent has only SELECT + INSERT on it, so entries can't be edited or
# deleted through the app.


def _split_actor(actor):
    """Return (integer id or None, display name). Never raises."""
    raw_id, name = actor if actor else (None, "unknown")
    name = name or "unknown"
    try:
        return int(raw_id), name
    except (TypeError, ValueError):
        if raw_id is not None:
            name = f"{name} [{raw_id}]"   # keep the non-numeric id visible
        return None, name


def write_audit(
    actor,
    action,
    table,
    row_count=None,
    old=None,
    new=None,
    sql_text=None,
    thread_id=None,
    status="success",
    cur=None,
):
    """
    Saves one audit entry.
    - cur=None: best-effort, own transaction (errors are logged, not raised).
    - cur=<cursor>: runs on the caller's transaction, does NOT commit, and
      errors propagate so the caller can roll the change back too.
    """
    actor_id, actor_name = _split_actor(actor)
    query = """
        INSERT INTO audit_log
        (actor_id, actor_name, thread_id, action, table_name,
         row_count, old_values, new_values, sql_text, status)
        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
    """
    params = (
        actor_id, actor_name, thread_id, action, table, row_count,
        json.dumps(old, default=str) if old is not None else None,
        json.dumps(new, default=str) if new is not None else None,
        sql_text, status,
    )

    if cur is not None:
        cur.execute(query, params)
        return

    try:
        with _pooled_cursor() as (conn, c):
            try:
                c.execute(query, params)
                conn.commit()
            except Exception:
                conn.rollback()
                raise
    except Exception:
        logger.exception("AUDIT WRITE FAILED: %s on %s by %s", action, table, actor)

def fetch_audit_logs(limit: int = 200, actor_id: int = None) -> list:
    """
    Returns the latest audit entries, newest first. Optionally filtered
    to a single person via actor_id. limit and actor_id are cast to int
    so nothing user-supplied can be injected into the query.
    """
    where = f"WHERE actor_id = {int(actor_id)}" if actor_id is not None else ""
    return fetch_rows(
        "SELECT id, occurred_at, actor_id, actor_name, action, table_name, "
        "row_count, old_values, new_values, status "
        f"FROM audit_log {where} ORDER BY occurred_at DESC LIMIT {int(limit)};"
    )


