def query_neo4j(cypher: str, params: dict = None) -> str:
    """
    Runs a Cypher statement against Neo4j. Pass user-controlled values via
    `params` (placeholders like $name) instead of interpolating them into
    the cypher string, to avoid injection/syntax issues.
    """
    try:
        with neo4j_driver.session() as session:
            result = session.run(cypher, params or {})
            records = [dict(record) for record in result]
            return str(records) if records else "OK, query executed."
    except Exception as e:
        logger.exception("query_neo4j failed.")
        return f"ERROR: {str(e)}"


def close_connections():
    """
    Call this on application shutdown (e.g. FastAPI lifespan/shutdown
    event in main.py) to release the connection pool and Neo4j driver
    cleanly instead of leaking them.
    """
    try:
        _pg_pool.closeall()
    except Exception:
        logger.exception("Failed to close Postgres pool.")
    try:
        neo4j_driver.close()
    except Exception:
        logger.exception("Failed to close Neo4j driver.")


