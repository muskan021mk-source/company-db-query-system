"""
MCP-style tools: give the agent read/write access to Postgres and Neo4j.

SECURITY MODEL (read this before changing thresholds/behavior):
- SQL is generated by an LLM from natural language, not typed by a trusted
  human. Treat every string that reaches query_postgres() as untrusted.
- App-level checks in agent.py (has_multiple_statements,
  contains_schema_change, has_where_clause) catch the obvious cases but are
  substring/regex checks, not a real parser -> they are a first line of
  defense only.
- The real safety net is the database itself:
        1. The Postgres role used here (app_agent) must NOT own any table and
       must NOT have CREATE on the schema. It can SELECT (RLS limited) and
       append to audit_log. User queries do not run as app_agent: they switch
       to agent_reader (reads) or agent_writer (writes) per request.
       No agent role has DELETE, and none can write to users. ALTER and DROP
       need table ownership and TRUNCATE is never granted, so Postgres
       rejects them even if the app-level checks are bypassed.
    2. Every write runs inside a transaction here, and if it would touch
       more rows than LARGE_WRITE_ROW_THRESHOLD, it is rolled back instead
       of committed, and the caller must re-run with confirm=True.
       NOTE: this is a PER-STATEMENT check only. agent.py additionally
       tracks a CUMULATIVE per-thread, per-table total across multiple
       run_sql_query calls in the same turn, so several writes that are
       each individually under this threshold can't add up to a large
       unconfirmed change. See _cumulative_write_rows in agent.py.
    3. Every connection gets a statement_timeout so a runaway/cartesian
       query can't hang or lock a table indefinitely.
    4. The audit_log table is append-only for app_agent (SELECT + INSERT
       only), so logged history cannot be edited or erased by the app.

Back up before testing:
    pg_dump -U postgres company_db > backup.sql
"""

